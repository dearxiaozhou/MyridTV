'use strict';
const assert = require('node:assert/strict');
require('../_internal/static/js/canvas-generation-lifecycle.js');
require('../_internal/static/js/canvas-ui-state.js');
const lifecycle = global.CanvasGenerationLifecycle;
const ui = global.CanvasUiState.create();
ui.patchSelection({primaryId:'editing-other'}, 'fixture');
const beforeUi = JSON.stringify(ui.snapshot());
const node = {w:704,h:396, pendingTasks:[{taskId:'old'}]};
lifecycle.lockFrame(node,{width:704,height:396});
const old = lifecycle.begin(node,{id:'old'});
assert.equal(node.pendingTasks, undefined);
lifecycle.transition(node,old,'queued');
lifecycle.transition(node,old,'running');
const current = lifecycle.begin(node,{id:'new'});
node.pending=2;node.running=true;node.apiRunning=true;
assert.equal(lifecycle.finish(node,old,'failed','old failure'), false);
assert.equal(node.pending,2);
assert.equal(node.runError,undefined);
node.cardSize={width:820,height:462};
assert.equal(lifecycle.finish(node,current,'failed','real failure',100),true);
assert.equal(node.runError,'real failure');
assert.equal(node.pending,0);
assert.equal(node.running,false);
assert.equal(node.apiRunning,false);
assert.deepEqual([node.w,node.h],[820,462]);
const retry = lifecycle.begin(node,{id:'retry'});
assert.equal(node.runError,undefined);
lifecycle.finish(node,retry,'cancelled');
assert.equal(lifecycle.isCurrent(node,retry),false);
assert.equal(lifecycle.finish(node,retry,'succeeded'),false);
assert.equal(node.generationState,'cancelled');
assert.equal(JSON.stringify(ui.snapshot()),beforeUi);
const invalid={w:704,h:396,cardSize:{width:NaN,height:0}};
assert.equal(lifecycle.restoreFrame(invalid,{width:512,height:288}),true);
assert.deepEqual(invalid.cardSize,{width:704,height:396});
assert.equal(lifecycle.lockFrame(invalid,{width:Infinity,height:50}),false);
console.log('PASS - stale attempts, cancellation, terminal flags, frame ownership and UI isolation');
