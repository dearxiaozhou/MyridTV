const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = vm.createContext({URL, location:{origin:'http://127.0.0.1:3107'}});
for(const file of ['canvas-generation-result-model','canvas-merge-sync']) vm.runInContext(fs.readFileSync('_internal/static/js/'+file+'.js','utf8'),ctx);
const m=ctx.CanvasMergeSync;
m.configure({smartPendingTasks:()=>[]});
const a={url:'/assets/a.png'},b={url:'/assets/b.png'},c={url:'/assets/c.png'};
const base={id:'n',title:'original',text:'old',x:10,images:[a]};
let merged=m.mergeChangedNode({...base,x:20},{...base,text:'',images:[b]},base);
assert.equal(merged.x,20); assert.equal(merged.text,''); assert.deepEqual(merged.images,[b]);
merged=m.mergeChangedNode({...base,images:[]},{...base,title:'remote'},base);
assert.equal(merged.images.length,0);
merged=m.mergeChangedNode({...base,images:[a,c]},{...base,images:[b]},base);
assert.deepEqual(Array.from(merged.images,i=>i.url),['/assets/b.png','/assets/c.png']);
assert.equal(m.mergeSmartNodeLists([base],[],[],[base]).length,0);
assert.equal(m.mergeSmartNodeLists([],[base],[],[base]).length,0);
assert.equal(m.mergeSmartNodeLists([{id:'new'}],[],[],[base]).length,1);
console.log('PASS: API image replacement/clear, text clear, local edits/additions, bidirectional node deletion');
